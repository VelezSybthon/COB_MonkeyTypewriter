/* ---------------- 倒计时控制（焦点驱动） ---------------- */
function updateTimerUI() {
  const v = $('#timerValue');
  if (v) {
    v.textContent = fmtTime(timer.remaining);
    v.classList.toggle('danger', timer.running && timer.remaining <= 60);
  }
  const st = $('#timerState');
  if (st) {
    st.textContent = !timer.started ? '未开始'
      : timer.running ? '进行中'
      : timer.finished ? '已结束'
      : '已暂停';
  }
}

function resumeTraining() {
  if (timer.finished || timer.running) return;
  timer.started = true;
  timer.running = true;
  timer.intervalId = setInterval(() => {
    timer.remaining = Math.max(0, timer.remaining - 1);
    updateTimerUI();
    if (timer.remaining === 0) {
      stopTimer();
      timer.finished = true;
      submitCheck(true); // 时间到，自动统计
    }
  }, 1000);
  updateTimerUI();
}

function pauseTraining() {
  if (!timer.running) return;
  stopTimer();
  updateTimerUI();
}

function resetTraining() {
  stopTimer();
  timer.remaining = TIMER_SECONDS;
  timer.started = false;
  timer.finished = false;
  scrollSyncEnabled = false; // 新一轮训练未开始：关闭滚动联动
  resetInputs();
  updateTimerUI();
}

function stopTimer() {
  if (timer.intervalId) { clearInterval(timer.intervalId); timer.intervalId = null; }
  timer.running = false;
}

